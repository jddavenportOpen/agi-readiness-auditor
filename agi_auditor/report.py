"""Render an audit result dict into a clean markdown GAP REPORT."""
from __future__ import annotations

import datetime as _dt
from typing import Any

_RATING_ICON = {
    "none": "🔴",
    "partial": "🟠",
    "substantial": "🟡",
    "strong": "🟢",
}
# how much "credit" each rating earns toward a readiness score
_RATING_SCORE = {"none": 0.0, "partial": 0.33, "substantial": 0.66, "strong": 1.0}


def _crit_by_id(framework: dict, cid: str) -> dict:
    for c in framework["criteria"]:
        if c["id"] == cid:
            return c
    return {"id": cid, "name": cid, "bar": "", "source": ""}


def readiness_score(result: dict) -> float:
    rs = result["results"]
    if not rs:
        return 0.0
    total = sum(_RATING_SCORE.get(r["rating"], 0.0) for r in rs)
    return round(100 * total / len(rs))


def render(result: dict[str, Any]) -> str:
    fw = result["framework"]
    company = result["company"]
    score = readiness_score(result)
    today = _dt.date.today().isoformat()

    lines: list[str] = []
    lines.append(f"# AGI Readiness Gap Report — {company}")
    lines.append("")
    lines.append(f"**Framework:** {fw['name']}  ")
    lines.append(f"**Date:** {today}  ")
    lines.append(
        f"**Public-claim coverage score:** {score}/100 "
        f"_(share of framework bars met by public claims)_  "
    )
    method = "LLM (claim→criterion mapping)" if result["llm_enabled"] else "deterministic keyword fallback"
    lines.append(f"**Analysis method:** {method}  ")
    lines.append(f"**Claims analyzed:** {result['claims_count']}")
    lines.append("")
    lines.append(
        "> **Scope:** This audits a company's PUBLIC, stated posture — blog posts, "
        "frameworks, model/system cards, public statements. It does **not** measure "
        "internal practice or whether claims are honored. A high score means the public "
        "story is complete, not that the company is safe."
    )
    lines.append("")

    # --- Summary table ---
    lines.append("## Summary")
    lines.append("")
    lines.append("| Criterion | Rating | Confidence | Method |")
    lines.append("|---|---|---|---|")
    for r in result["results"]:
        c = _crit_by_id(fw, r["criterion_id"])
        icon = _RATING_ICON.get(r["rating"], "")
        lines.append(
            f"| {c['name']} | {icon} {r['rating']} | {r['confidence']:.0%} | {r['method']} |"
        )
    lines.append("")

    # --- Per-criterion detail ---
    lines.append("## Detail")
    lines.append("")
    for r in result["results"]:
        c = _crit_by_id(fw, r["criterion_id"])
        icon = _RATING_ICON.get(r["rating"], "")
        lines.append(f"### {icon} {c['name']} — **{r['rating']}**")
        lines.append("")
        lines.append(f"**Bar:** {c['bar']}")
        lines.append("")
        lines.append(f"**Framework source:** {c['source']}")
        lines.append("")
        if r["evidence"]:
            lines.append("**Evidence (public claims):**")
            for ev in r["evidence"]:
                lines.append(f"> {ev['text']}")
                lines.append(f"> — source: {ev['source']}")
                lines.append("")
        else:
            lines.append("**Evidence:** _none found in corpus._")
            lines.append("")
        lines.append(f"**Gap assessment:** {r['gap']}")
        lines.append("")
        lines.append(f"**Confidence:** {r['confidence']:.0%}")
        lines.append("")
        lines.append("---")
        lines.append("")

    # --- Biggest gaps callout ---
    gaps = [r for r in result["results"] if r["rating"] in ("none", "partial")]
    lines.append("## Where the public posture falls short")
    lines.append("")
    if gaps:
        for r in gaps:
            c = _crit_by_id(fw, r["criterion_id"])
            lines.append(f"- **{c['name']}** ({r['rating']}): {r['gap']}")
    else:
        lines.append("- No criterion rated below `substantial` on public claims.")
    lines.append("")

    # --- Methodology / framework sources ---
    lines.append("## Methodology & sources")
    lines.append("")
    lines.append(f"Framework definition: **{fw['name']}**")
    lines.append("")
    for s in fw.get("sources", []):
        lines.append(f"- {s}")
    lines.append("")
    lines.append(
        "Ratings: 🔴 none · 🟠 partial · 🟡 substantial · 🟢 strong. Each criterion is "
        "scored on whether the company's *public claims* meet the framework's *bar* — "
        "the specific, citable threshold above. Evidence quotes link to public sources so "
        "every claim in this report is independently checkable."
    )
    lines.append("")
    lines.append("_Generated by [AGI Readiness Auditor](https://github.com/JDDavenport/agi-readiness-auditor)._")
    lines.append("")
    return "\n".join(lines)
